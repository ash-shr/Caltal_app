-- Places a person has named (Home, Work, the gym) so they can pin a task to
-- one in a tap instead of finding it on the map every time.
CREATE TABLE saved_place (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id  BIGINT NOT NULL REFERENCES app_user(id),
    name      VARCHAR(50) NOT NULL,
    -- The name in lower case, so "Home" and "home" count as the same name
    -- even when two saves arrive at the same moment.
    name_key  VARCHAR(50) NOT NULL,
    latitude  DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    address   VARCHAR(255),

    -- One "Home" per person. Also serves as the index for "this person's places".
    CONSTRAINT uq_saved_place_owner_name UNIQUE (owner_id, name_key)
);
