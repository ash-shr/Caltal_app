-- Six-digit codes emailed to confirm a new account's address. Someone signing
-- up types the code into the app or website, which proves the address is
-- theirs before the account can be used.
--
-- Only a BCrypt hash of each code is kept. A code has just a million possible
-- values, so a plain fast hash could be reversed by trying them all; BCrypt
-- makes that slow. Wrong guesses are counted, and a code stops working after
-- a few, so guessing over the internet doesn't work either.
CREATE TABLE email_code (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES app_user(id),
    code_hash  VARCHAR(100) NOT NULL,
    attempts   INTEGER NOT NULL DEFAULT 0,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Set once the code has been used, or replaced by a newer one
    used_at    TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- "This person's latest code", and "how many codes in the last hour?"
CREATE INDEX idx_email_code_user ON email_code (user_id, created_at);
