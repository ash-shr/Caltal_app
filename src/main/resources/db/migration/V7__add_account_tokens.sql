-- One-time links sent by email: "confirm your email" and "reset your password".
--
-- Only a SHA-256 hash of each link's secret is kept, never the secret itself,
-- so someone who gets a copy of the database still can't use the links.
CREATE TABLE account_token (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES app_user(id),
    -- VERIFY_EMAIL or RESET_PASSWORD
    purpose    VARCHAR(30) NOT NULL,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Set the moment a link is used. A used link never works again.
    used_at    TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- "How many links has this person been sent in the last hour?"
CREATE INDEX idx_account_token_user_purpose ON account_token (user_id, purpose, created_at);
